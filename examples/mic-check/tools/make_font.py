#!/usr/bin/env python3
"""Rasterizes the glyphs mic-check shows into main/font_data.inc (4-bit anti-aliased bitmaps).

    python3 tools/make_font.py --fonts <folder with HarmonyOS_Sans_SC_{Regular,Medium,Bold}.ttf>

The characters: printable ASCII and every non-ASCII character in main/*.cpp and main/*.h for the two small
sizes; what the larger ones show (MEDIUM, LARGE, DIGITS below) for the others. HarmonyOS Sans SC is the font
the HAL's system menu uses (licenses/HarmonyOS-Sans-LICENSE.txt); the TTF files are not in the repository.
Needs Pillow and fontTools. The host test (test/) fails when a screen draws a character the font lacks.
"""

import argparse
import pathlib
import re

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent.parent
ASCII = "".join(chr(code) for code in range(0x20, 0x7F))
LARGE = "麦克风收音测试保持安静轻声说话正常大拍手机外放乐"
MEDIUM = ASCII + "距离厘米不用动" + LARGE
DIGITS = "0123456789"
# name, file, pixel size, characters ("" = ASCII and every non-ASCII character of the sources)
FONTS = [
    ("kTiny", "Regular", 12, ""),
    ("kSmall", "Regular", 14, ""),
    ("kMedium", "Medium", 18, MEDIUM),
    ("kLarge", "Medium", 26, LARGE),
    ("kDigits", "Bold", 52, DIGITS),
]


def source_characters():
    found = set()
    for path in sorted((HERE / "main").glob("*.[ch]*")):
        if path.name == "font_data.inc":
            continue
        found.update(ch for ch in path.read_text(encoding="utf-8") if ord(ch) > 0x7E)
    return "".join(sorted(found))


def rasterize(font_path, size, characters):
    font = ImageFont.truetype(str(font_path), size)
    cmap = TTFont(str(font_path)).getBestCmap()
    missing = [ch for ch in characters if ord(ch) not in cmap and ch != " "]
    if missing:
        raise SystemExit(f"{font_path.name} has no glyph for {''.join(missing)!r}")
    # The line: from the top of a CJK character or a capital to the lowest descender, of those the font shows.
    references = [ch for ch in "Hgjpy0" if ch in characters]
    if any(ord(ch) > 0x2E7F for ch in characters):
        references.append("国")
    line_top = min(font.getbbox(ch, anchor="ls")[1] for ch in references)
    line_bottom = max(font.getbbox(ch, anchor="ls")[3] for ch in references)
    glyphs = []
    for ch in sorted(set(characters), key=ord):
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        width, height = max(0, right - left), max(0, bottom - top)
        alpha = []
        if width and height:
            image = Image.new("L", (width, height), 0)
            ImageDraw.Draw(image).text((-left, -top), ch, font=font, fill=255, anchor="ls")
            alpha = [(value * 15 + 127) // 255 for value in image.tobytes()]
        glyphs.append((ord(ch), left, top - line_top, width, height, round(font.getlength(ch)), alpha))
    return glyphs, line_bottom - line_top


def emit(name, glyphs, height):
    lines = []
    packed = bytearray()
    entries = []
    for code, left, top, width, height_, advance, alpha in glyphs:
        offset = len(packed)
        nibbles = alpha + ([0] if len(alpha) % 2 else [])
        packed.extend(nibbles[index] | nibbles[index + 1] << 4 for index in range(0, len(nibbles), 2))
        entries.append(f"    {{0x{code:04X}, {left}, {top}, {width}, {height_}, {advance}, {offset}}},")
    lines.append(f"const uint8_t {name}Alpha[] = {{")
    for start in range(0, len(packed), 24):
        lines.append("    " + ",".join(str(byte) for byte in packed[start:start + 24]) + ",")
    lines.append("};")
    lines.append(f"const Glyph {name}Glyphs[] = {{")
    lines.extend(entries)
    lines.append("};")
    lines.append(f"const Font {name} = {{{name}Glyphs, {len(glyphs)}, {height}, {name}Alpha}};")
    return lines, len(packed)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fonts", required=True, type=pathlib.Path, help="folder with HarmonyOS_Sans_SC_*.ttf")
    args = parser.parse_args()
    text = source_characters()
    out = [
        "// Generated by tools/make_font.py from HarmonyOS Sans SC (licenses/HarmonyOS-Sans-LICENSE.txt): do not edit.",
        f"// Characters: printable ASCII and {text}",
        "",
    ]
    total = 0
    for name, weight, size, characters in FONTS:
        glyphs, height = rasterize(args.fonts / f"HarmonyOS_Sans_SC_{weight}.ttf", size, characters or ASCII + text)
        lines, size_bytes = emit(name, glyphs, height)
        out.extend(lines)
        out.append("")
        total += size_bytes + len(glyphs) * 12
        print(f"{name}: {len(glyphs)} glyphs, line {height} px, {size_bytes} bytes of alpha")
    (HERE / "main" / "font_data.inc").write_text("\n".join(out), encoding="utf-8")
    print(f"main/font_data.inc: about {total} bytes in the image")


if __name__ == "__main__":
    main()
